"""Specs: the current requirements of each capability, built from the applied spec deltas.

A spec delta (`<plans>/<plan-id>.spec.md`) adds, changes, or removes requirements. `stone spec
apply` gives the delta the next `apply_order` and writes the specs (`<specs>/<capability>.md`).
The specs are generated: a replay of all applied deltas, in order, must give the same files.
"""

from __future__ import annotations

import copy
import re
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from stone.markdown import split_frontmatter

CONFIG = Path(".cornerstone/config.yaml")
DEFAULT_PATHS = {"plans": "docs/plans/", "specs": "docs/specs/"}
DELTA_SUFFIX = ".spec.md"
HEADER = ("<!-- Generated by stone spec apply. Do not edit. Change the spec delta of a plan, "
          "and apply it. -->")
CHANGE = re.compile(r"^## (?P<op>ADDED|MODIFIED|REMOVED) (?P<id>\S+): (?P<title>\S.*)$")
REQUIREMENT_ID = re.compile(r"^(?P<capability>[a-z][a-z0-9-]*)\.R(?P<number>[1-9]\d*)$")
SCENARIO = re.compile(r"^### Scenario: \S")
STEP = re.compile(r"^\s*(?:[-*]\s+)?\**(?P<word>WHEN|THEN)\b")
HEADING = re.compile(r"^#{1,3} ")  # a #### heading can be part of a scenario
FENCE = ("```", "~~~")
ORDER_LINE = re.compile(r"^apply_order:.*$", re.M)


class SpecError(Exception):
    """A delta or a spec is not valid. Nothing was written."""


@dataclass
class Change:
    op: str
    id: str
    title: str
    body: str
    line: int


@dataclass
class Delta:
    plan: str
    path: Path
    order: int | None
    changes: list[Change] = field(default_factory=list)
    errors: list[tuple[int, str]] = field(default_factory=list)


@dataclass
class Requirement:
    id: str
    title: str
    body: str
    removed: bool = False  # a removed number is kept, so it is not used again


State = dict[str, dict[int, Requirement]]  # capability -> requirement number -> requirement


def config_path(root: Path, key: str) -> Path:
    """Return `paths.<key>` from the repo config, or the default."""
    value = None
    if (root / CONFIG).exists():
        try:
            data = yaml.safe_load((root / CONFIG).read_text(encoding="utf-8")) or {}
        except yaml.YAMLError as error:
            raise SpecError(f"{CONFIG}: the YAML is not valid: {error}") from None
        paths = data.get("paths") if isinstance(data, dict) else None
        value = paths.get(key) if isinstance(paths, dict) else None
    path = (root / (value or DEFAULT_PATHS[key])).resolve()
    if not path.is_relative_to(root.resolve()):
        raise SpecError(f"{CONFIG}: 'paths.{key}' is outside the repo. Use a path in the repo.")
    return path


def parse_delta(path: Path) -> Delta:
    """Read one delta. Record each format error with its line number."""
    text = path.read_text(encoding="utf-8")
    delta = Delta(path.name[: -len(DELTA_SUFFIX)], path, None)
    try:
        meta, skip = split_frontmatter(text)
    except yaml.YAMLError:
        meta, skip = {}, 0
        delta.errors.append((1, "The frontmatter is not valid YAML. Fix it."))
    if not isinstance(meta, dict):
        meta = {}
        delta.errors.append((1, "The frontmatter must be 'key: value' lines."))
    order = meta.get("apply_order")
    if order is not None and (not isinstance(order, int) or isinstance(order, bool) or order < 1):
        delta.errors.append((1, "'apply_order' must be a whole number from 1."))
    else:
        delta.order = order
    current: Change | None = None
    body: list[str] = []
    in_code = False
    for number, line in enumerate(text.splitlines()[skip:], skip + 1):
        if line.lstrip().startswith(FENCE):
            in_code = not in_code
        if not in_code and line.startswith("## "):
            _close(delta, current, body)
            current, body = _open(delta, line, number), []
        elif current:
            body.append(line)
    _close(delta, current, body)
    if not delta.changes and not delta.errors:
        delta.errors.append((1, "The delta has no change. Add an ADDED, MODIFIED, or REMOVED "
                                "section, or delete the file."))
    return delta


def _open(delta: Delta, line: str, number: int) -> Change | None:
    match = CHANGE.match(line)
    if not match:
        delta.errors.append((number, "A change heading must be '## ADDED|MODIFIED|REMOVED "
                                     "<capability>.R<n>: <title>'."))
        return None
    if not REQUIREMENT_ID.match(match["id"]):
        delta.errors.append((number, f"'{match['id']}' is not a requirement ID. Use "
                                     "<capability>.R<n>, for example export.R1."))
        return None
    if any(change.id == match["id"] for change in delta.changes):
        delta.errors.append((number, f"The delta changes {match['id']} two times. Merge the "
                                     "sections."))
        return None
    return Change(match["op"], match["id"], match["title"].strip(), "", number)


def _close(delta: Delta, change: Change | None, body: list[str]) -> None:
    if change is None:
        return
    change.body = "\n".join(body).strip("\n")
    if change.op != "REMOVED":
        problem = _scenario_problem(body)
        if problem:
            delta.errors.append((change.line, f"{change.id} {problem}"))
            return
    delta.changes.append(change)


def _scenario_problem(body: list[str]) -> str:
    """Return what is wrong with the scenarios of one requirement, or an empty string."""
    scenarios: list[set[str]] = []
    in_scenario = in_code = False
    for line in body:
        if line.lstrip().startswith(FENCE):
            in_code = not in_code
        elif in_code:
            continue
        elif SCENARIO.match(line):
            scenarios.append(set())
            in_scenario = True
        elif HEADING.match(line):
            in_scenario = False
        elif in_scenario and (step := STEP.match(line)):
            scenarios[-1].add(step["word"])
    if not scenarios:
        return "has no scenario. Add a '### Scenario: <name>' with WHEN and THEN lines."
    if any(words != {"WHEN", "THEN"} for words in scenarios):
        return "has a scenario with no WHEN line or no THEN line. Add both."
    return ""


def load_deltas(root: Path) -> dict[str, Delta]:
    folder = config_path(root, "plans")
    return {delta.plan: delta for delta in
            (parse_delta(path) for path in sorted(folder.glob("*" + DELTA_SUFFIX)))}


def apply_delta(state: State, delta: Delta) -> None:
    """Apply each change of one delta to the state. Raise SpecError on a conflict."""
    for change in delta.changes:
        match = REQUIREMENT_ID.match(change.id)
        assert match
        requirements = state.setdefault(match["capability"], {})
        number = int(match["number"])
        old = requirements.get(number)
        where = f"{delta.path.name}:{change.line}"
        if change.op == "ADDED" and old:
            reason = "was removed. Do not use a removed number again" if old.removed else "exists"
            raise SpecError(f"{where}: {change.id} {reason}. Use MODIFIED, or a new number.")
        if change.op != "ADDED" and (not old or old.removed):
            raise SpecError(f"{where}: {change.id} does not exist, so it cannot be "
                            f"{change.op.lower()}.")
        requirements[number] = Requirement(change.id, change.title, change.body,
                                           removed=change.op == "REMOVED")


def applied(deltas: dict[str, Delta]) -> list[Delta]:
    """Return the applied deltas in apply order. A tie is sorted by plan ID."""
    return sorted((d for d in deltas.values() if d.order is not None),
                  key=lambda d: (d.order or 0, d.plan))


def replay(deltas: list[Delta]) -> State:
    state: State = {}
    for delta in deltas:
        apply_delta(state, delta)
    return state


def render_specs(state: State) -> dict[str, str]:
    """Return the text of each spec file, by file name."""
    files = {}
    for capability in sorted(state):
        live = [state[capability][n] for n in sorted(state[capability])
                if not state[capability][n].removed]
        if not live:
            continue
        parts = [HEADER, f"# {capability}"]
        for requirement in live:
            parts.append(f"## {requirement.id}: {requirement.title}")
            if requirement.body:
                parts.append(requirement.body)
        files[f"{capability}.md"] = "\n\n".join(parts) + "\n"
    return files


def drift(folder: Path, expected: dict[str, str]) -> list[str]:
    """Return each spec file name that is not the same as the replay."""
    on_disk = {path.name for path in folder.glob("*.md")} if folder.is_dir() else set()
    return sorted(name for name in on_disk | set(expected)
                  if name not in expected or name not in on_disk
                  or (folder / name).read_text(encoding="utf-8") != expected[name])


def set_order(text: str, order: int) -> str:
    """Return the delta text with `apply_order: <order>` in its frontmatter."""
    _, skip = split_frontmatter(text)
    if not skip:
        return f"---\napply_order: {order}\n---\n\n{text}"
    lines = text.split("\n")
    front = [line for line in lines[1 : skip - 1] if not ORDER_LINE.match(line)]
    return "\n".join(["---", f"apply_order: {order}", *front, *lines[skip - 1 :]])


def apply(root: Path, plan: str) -> list[str]:
    """Apply the delta of one plan. Return the paths that changed, relative to root."""
    deltas = load_deltas(root)
    if plan not in deltas:
        folder = config_path(root, "plans").relative_to(root.resolve()).as_posix()
        raise SpecError(f"No spec delta for '{plan}'. Write {folder}/{plan}{DELTA_SUFFIX} first.")
    target = deltas[plan]
    if target.order is not None:
        raise SpecError(f"{target.path.name}: the delta is applied (apply_order: "
                        f"{target.order}). Write a new plan for a new change.")
    for delta in deltas.values():
        if delta.errors:
            line, message = delta.errors[0]
            raise SpecError(f"{delta.path.name}:{line}: {message}")
    history = applied(deltas)
    state = replay(history)
    folder = config_path(root, "specs")
    changed = drift(folder, render_specs(state))
    if changed:
        raise SpecError(f"Drift in {', '.join(changed)}: the specs are not the same as a replay "
                        "of the applied deltas. Undo the edit (git checkout), and change a delta instead.")
    new_state = copy.deepcopy(state)
    apply_delta(new_state, target)
    expected = render_specs(new_state)
    order = max((d.order or 0 for d in history), default=0) + 1
    written = []
    folder.mkdir(parents=True, exist_ok=True)
    for name in drift(folder, expected):
        path = folder / name
        if name in expected:
            path.write_text(expected[name], encoding="utf-8")
        else:
            path.unlink()
        written.append(path)
    # Write the delta last, so that a failed spec write never marks it as applied.
    target.path.write_text(set_order(target.path.read_text(encoding="utf-8"), order),
                           encoding="utf-8")
    written.insert(0, target.path)
    base = root.resolve()
    return [path.resolve().relative_to(base).as_posix() for path in written]
